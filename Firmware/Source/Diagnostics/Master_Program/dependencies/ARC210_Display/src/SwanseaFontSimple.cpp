// GET SWANSEA STRING WIDTH
// Supports fractional scaling
// ==================================================
int16_t getSwanseaTextWidth(
    const char* text,
    float scale
)
{
    if (text == nullptr || scale <= 0.0f)
    {
        return 0;
    }

    int16_t width = 0;

    while (*text)
    {
        char c = *text++;

        if (c < SWANSEA_FIRST || c > SWANSEA_LAST)
        {
            continue;
        }

        uint8_t index =
            (uint8_t)c - SWANSEA_FIRST;

        SwanseaSimpleGlyph g;

        memcpy_P(
            &g,
            &Swansea28GlyphsSimple[index],
            sizeof(SwanseaSimpleGlyph)
        );

        width += roundf(
            g.xAdvance * scale
        );
    }

    return width;
}